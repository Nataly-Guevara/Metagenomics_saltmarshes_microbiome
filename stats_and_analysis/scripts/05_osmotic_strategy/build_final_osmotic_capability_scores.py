def write_capability_prevalence(scored_rows):
    """
    Write uncorrected overall prevalence for each final capability.

    This is not the Ricci group-level completeness correction.
    """
    total_mags = len(scored_rows)

    columns = [
        "Capability",
        "Final_output_column",
        "Positive_MAGs",
        "Total_MAGs",
        "Observed_prevalence_percent",
        "Completeness_correction_applied",
    ]

    with open(
        FINAL_PREVALENCE_OUTPUT,
        "w",
        encoding="utf-8",
        newline="",
    ) as handle:
        writer = csv.DictWriter(
            handle,
            fieldnames=columns,
            delimiter="\t",
        )

        writer.writeheader()

        for capability in PRIMARY_CAPABILITIES:
            column = capability["final_column"]

            positive = sum(
                int(row[column])
                for row in scored_rows
            )

            prevalence = (
                100.0 * positive / total_mags
            )

            writer.writerow(
                {
                    "Capability": capability["capability"],
                    "Final_output_column": column,
                    "Positive_MAGs": positive,
                    "Total_MAGs": total_mags,
                    "Observed_prevalence_percent": (
                        f"{prevalence:.2f}"
                    ),
                    "Completeness_correction_applied": "No",
                }
            )


def write_score_distribution(scored_rows):
    """
    Write the full 0-5 score distribution.
    """
    distribution = Counter(
        int(row["Osmotic_capability_count_0_5"])
        for row in scored_rows
    )

    total_mags = len(scored_rows)

    columns = [
        "Capability_count",
        "Proportional_score",
        "MAGs",
        "Total_MAGs",
        "Prevalence_percent",
    ]

    with open(
        FINAL_SCORE_DISTRIBUTION_OUTPUT,
        "w",
        encoding="utf-8",
        newline="",
    ) as handle:
        writer = csv.DictWriter(
            handle,
            fieldnames=columns,
            delimiter="\t",
        )

        writer.writeheader()

        for score in range(0, 6):
            mag_count = distribution.get(score, 0)

            writer.writerow(
                {
                    "Capability_count": score,
                    "Proportional_score": f"{score / 5.0:.4f}",
                    "MAGs": mag_count,
                    "Total_MAGs": total_mags,
                    "Prevalence_percent": (
                        f"{100.0 * mag_count / total_mags:.2f}"
                    ),
                }
            )


