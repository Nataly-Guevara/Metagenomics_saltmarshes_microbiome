def print_summary(scored_rows):
    """
    Print a concise terminal summary.
    """
    total_mags = len(scored_rows)

    print("Final osmotic capability scoring completed.")
    print()
    print(f"MAGs scored: {total_mags}")
    print("Primary capabilities: 5")
    print()
    print(f"Final MAG matrix: {FINAL_MATRIX_OUTPUT}")
    print(f"Final rules table: {FINAL_RULES_OUTPUT}")
    print(
        "Uncorrected capability prevalence: "
        f"{FINAL_PREVALENCE_OUTPUT}"
    )
    print(
        "Primary score distribution: "
        f"{FINAL_SCORE_DISTRIBUTION_OUTPUT}"
    )
    print(
        "Sensitivity score distribution: "
        f"{SENSITIVITY_DISTRIBUTION_OUTPUT}"
    )
    print()

    print("Final capability prevalence")
    print("---------------------------")

    for capability in PRIMARY_CAPABILITIES:
        column = capability["final_column"]

        positive = sum(
            int(row[column])
            for row in scored_rows
        )

        prevalence = (
            100.0 * positive / total_mags
        )

        print(
            f"{capability['capability']:<38}"
            f"{positive:>5} MAGs  "
            f"({prevalence:>6.2f}%)"
        )

    primary_distribution = Counter(
        int(row["Osmotic_capability_count_0_5"])
        for row in scored_rows
    )

    print()
    print("Primary osmotic capability-score distribution")
    print("---------------------------------------------")

    for score in range(0, 6):
        mag_count = primary_distribution.get(score, 0)
        prevalence = (
            100.0 * mag_count / total_mags
        )

        print(
            f"{score}/5: "
            f"{mag_count} MAGs "
            f"({prevalence:.2f}%)"
        )

    sensitivity_distribution = Counter(
        int(
            row[
                "Osmotic_capability_count_without_channels_0_4"
            ]
        )
        for row in scored_rows
    )

    print()
    print("Sensitivity distribution without channels")
    print("-----------------------------------------")

    for score in range(0, 5):
        mag_count = sensitivity_distribution.get(score, 0)
        prevalence = (
            100.0 * mag_count / total_mags
        )

        print(
            f"{score}/4: "
            f"{mag_count} MAGs "
            f"({prevalence:.2f}%)"
        )

    print()
    print(
        "No genome-level completeness correction was applied."
    )


def main():
    os.makedirs(
        OUTPUT_DIR,
        exist_ok=True,
    )

    rows, input_columns = read_presence_matrix()

    scored_rows = calculate_final_scores(rows)

    output_columns = build_output_columns(input_columns)

    write_final_matrix(
        scored_rows,
        output_columns,
    )

    write_final_rules_table()

    write_capability_prevalence(scored_rows)

    write_score_distribution(scored_rows)

    write_sensitivity_distribution(scored_rows)

    print_summary(scored_rows)


if __name__ == "__main__":
    main()

