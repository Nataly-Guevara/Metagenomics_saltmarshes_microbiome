def parse_binary(value, column_name, mag_name):
    """
    Convert a value to binary integer 0 or 1.

    Stop with an informative error if a source capability column
    contains anything else.
    """
    cleaned = str(value).strip()

    if cleaned in {"0", "0.0"}:
        return 0

    if cleaned in {"1", "1.0"}:
        return 1

    sys.exit(
        "ERROR: Non-binary value found.\n"
        f"MAG: {mag_name}\n"
        f"Column: {column_name}\n"
        f"Value: {value}"
    )


def parse_nonnegative_integer(value, column_name, mag_name):
    """
    Parse an integer-valued diagnostic field.
    """
    cleaned = str(value).strip()

    try:
        number = int(float(cleaned))
    except ValueError:
        sys.exit(
            "ERROR: Non-integer diagnostic value found.\n"
            f"MAG: {mag_name}\n"
            f"Column: {column_name}\n"
            f"Value: {value}"
        )

    if number < 0:
        sys.exit(
            "ERROR: Negative diagnostic value found.\n"
            f"MAG: {mag_name}\n"
            f"Column: {column_name}\n"
            f"Value: {value}"
        )

    return number


def read_presence_matrix():
    """
    Read the V2 capability-presence matrix and validate required columns.
    """
    try:
        handle = open(
            INPUT_FILE,
            "r",
            encoding="utf-8-sig",
            newline="",
        )
    except OSError as exc:
        sys.exit(
            "ERROR: Could not open input file:\n"
            f"{INPUT_FILE}\n"
            f"{exc}"
        )

    with handle:
        reader = csv.DictReader(
            handle,
            delimiter="\t",
        )

        if reader.fieldnames is None:
            sys.exit(
                "ERROR: Input file does not contain a header."
            )

        required_columns = {"Final_MAG"}

        required_columns.update(
            item["source_column"]
            for item in PRIMARY_CAPABILITIES
        )

        required_columns.update(
            SECONDARY_ROUTE_COLUMNS
        )

        missing_columns = sorted(
            required_columns.difference(reader.fieldnames)
        )

        if missing_columns:
            sys.exit(
                "ERROR: Required columns are missing from the V2 "
                "presence matrix:\n"
                + "\n".join(missing_columns)
            )

        rows = []
        seen_mags = set()

        for row in reader:
            mag = (row.get("Final_MAG") or "").strip()

            if not mag:
                continue

            if mag in seen_mags:
                sys.exit(
                    "ERROR: Duplicate MAG found in the presence matrix:\n"
                    f"{mag}"
                )

            seen_mags.add(mag)
            rows.append(row)

        fieldnames = list(reader.fieldnames)

    if not rows:
        sys.exit(
            "ERROR: No MAG rows were found in the input matrix."
        )

    return rows, fieldnames


def calculate_final_scores(rows):
    """
    Add final binary capability calls, primary scores, route counts,
    and sensitivity scores to every MAG.
    """
    scored_rows = []

    for row in rows:
        mag = row["Final_MAG"]

        final_calls = {}

        for capability in PRIMARY_CAPABILITIES:
            source_column = capability["source_column"]
            final_column = capability["final_column"]

            final_calls[final_column] = parse_binary(
                row[source_column],
                source_column,
                mag,
            )

        primary_count = sum(
            final_calls[capability["final_column"]]
            for capability in PRIMARY_CAPABILITIES
        )

        primary_score = primary_count / 5.0

        channel_column = "Osmotic_Mechanosensitive_channel"

        count_without_channels = (
            primary_count - final_calls[channel_column]
        )

        score_without_channels = (
            count_without_channels / 4.0
        )

        trehalose_route_count = (
            parse_binary(
                row["Trehalose_OtsAB"],
                "Trehalose_OtsAB",
                mag,
            )
            +
            parse_binary(
                row["Trehalose_bifunctional_K16055"],
                "Trehalose_bifunctional_K16055",
                mag,
            )
        )

        compatible_solute_route_count = (
            parse_binary(
                row[
                    "Osmoprotectant_transporter_"
                    "K05845_K05846_K05847"
                ],
                (
                    "Osmoprotectant_transporter_"
                    "K05845_K05846_K05847"
                ),
                mag,
            )
            +
            parse_binary(
                row["ProVWX_transporter_K02000_K02001_K02002"],
                "ProVWX_transporter_K02000_K02001_K02002",
                mag,
            )
        )

        sodium_route_count = (
            parse_binary(
                row["Sodium_NatAB_K09696_K09697"],
                "Sodium_NatAB_K09696_K09697",
                mag,
            )
            +
            parse_binary(
                row["Sodium_H_antiporter_K24160"],
                "Sodium_H_antiporter_K24160",
                mag,
            )
            +
            parse_binary(
                row["Sodium_pumping_pyrophosphatase_K15987"],
                "Sodium_pumping_pyrophosphatase_K15987",
                mag,
            )
        )

        parse_nonnegative_integer(
            row["Mechanosensitive_channel_class_count"],
            "Mechanosensitive_channel_class_count",
            mag,
        )

        output_row = dict(row)
        output_row.update(final_calls)

        output_row[
            "Osmotic_capability_count_0_5"
        ] = primary_count

        output_row[
            "Osmotic_capability_score_0_1"
        ] = f"{primary_score:.4f}"

        output_row[
            "Osmotic_capability_count_without_channels_0_4"
        ] = count_without_channels

        output_row[
            "Osmotic_capability_score_without_channels_0_1"
        ] = f"{score_without_channels:.4f}"

        output_row[
            "Trehalose_route_count"
        ] = trehalose_route_count

        output_row[
            "Compatible_solute_uptake_route_count"
        ] = compatible_solute_route_count

        output_row[
            "Sodium_homeostasis_route_count"
        ] = sodium_route_count

        scored_rows.append(output_row)

    return scored_rows


def build_output_columns(input_columns):
    """
    Preserve all V2 columns and append final selected capabilities
    and score fields.
    """
    final_capability_columns = [
        capability["final_column"]
        for capability in PRIMARY_CAPABILITIES
    ]

    appended_columns = (
        final_capability_columns
        + PRIMARY_SCORE_COLUMNS
    )

    output_columns = list(input_columns)

    for column in appended_columns:
        if column not in output_columns:
            output_columns.append(column)

    return output_columns


def write_final_matrix(scored_rows, output_columns):
    """
    Write the complete final MAG-level matrix.
    """
    with open(
        FINAL_MATRIX_OUTPUT,
        "w",
        encoding="utf-8",
        newline="",
    ) as handle:
        writer = csv.DictWriter(
            handle,
            fieldnames=output_columns,
            delimiter="\t",
            extrasaction="ignore",
        )

        writer.writeheader()

        for row in scored_rows:
            writer.writerow(row)


